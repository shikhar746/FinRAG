"""Parse every PDF into data/pages.parquet and log suspicious pages.

Outputs:
  data/pages.parquet          one row per PDF page: doc_name, page (0-based), text, n_chars
  data/parse_failures.csv     pages that failed to parse or have (almost) no text
  results/ingest_report.md    counts + gold-page alignment check (committed)
"""
import argparse
from pathlib import Path

from finrag.ingest import check_gold_alignment, gold_pages, load_questions, parse_all

ALIGN_OK = 0.8  # a gold page "matches" if >=80% of the dataset's page words are on our page


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", default="data")
    ap.add_argument("--report", default="results/ingest_report.md")
    args = ap.parse_args()
    data = Path(args.data)

    pages, failures = parse_all(data / "pdfs")
    pages.to_parquet(data / "pages.parquet", index=False)
    failures.to_csv(data / "parse_failures.csv", index=False)

    questions = load_questions(data / "raw/financebench_open_source.jsonl")
    align = check_gold_alignment(questions, pages)
    align.to_csv(data / "gold_alignment.csv", index=False)
    best = align[["overlap_-1", "overlap_+0", "overlap_+1"]].idxmax(axis=1).value_counts()

    gold = {(q["doc_name"], p) for q in questions for p in gold_pages(q)}
    failed = set(zip(failures.doc_name, failures.page))
    n_docs = pages.doc_name.nunique()

    lines = [
        "#### Ingestion report",
        "",
        "Generated by `scripts/ingest.py`.",
        "",
        f"- PDFs parsed: {n_docs}",
        f"- Pages: {len(pages)}",
        f"- Pages logged as failures: {len(failures)} "
        f"({', '.join(f'{k}: {v}' for k, v in failures.reason.value_counts().items()) or 'none'})",
        f"- Distinct gold evidence pages: {len(gold)}; of these logged as failures: {len(gold & failed)}",
        "",
        "#### Gold page-number convention check",
        "",
        "For each gold evidence item we measure word overlap between the dataset's",
        "`evidence_text_full_page` and our parsed page at index `evidence_page_num + offset`.",
        "",
        "| offset | evidence items where this offset matches best |",
        "|---|---|",
        *[f"| {k.removeprefix('overlap_')} | {v} |" for k, v in best.items()],
        "",
        f"- Evidence items with overlap >= {ALIGN_OK} at offset 0: "
        f"{(align['overlap_+0'] >= ALIGN_OK).sum()} / {len(align)}",
        f"- Median overlap at offset 0: {align['overlap_+0'].median():.3f}",
        "",
    ]
    Path(args.report).parent.mkdir(exist_ok=True)
    Path(args.report).write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
